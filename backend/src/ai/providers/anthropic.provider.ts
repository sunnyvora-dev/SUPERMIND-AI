import { Injectable } from '@nestjs/common';
import { AIProvider, AIRequest, AIResponse } from './ai-provider.interface';

@Injectable()
export class AnthropicProvider implements AIProvider {
  getProviderName(): string {
    return 'Anthropic';
  }

  getCapabilities(): string[] {
    return ['CODING', 'COMPLEX_REASONING', 'REFACTORED_SYNTAX'];
  }

  isAvailable(): boolean {
    return true;
  }

  async generate(request: AIRequest): Promise<AIResponse> {
    const startTime = Date.now();
    await new Promise((r) => setTimeout(r, 480));

    return {
      content: `[Claude 3.5 Sonnet Response]\n\nHere is the requested implementation generated by Claude 3.5 Sonnet:\n\n${request.prompt}`,
      providerName: 'Anthropic',
      modelName: 'Claude 3.5 Sonnet',
      promptTokens: Math.floor(request.prompt.length / 4) + 60,
      completionTokens: 180,
      totalTokens: Math.floor(request.prompt.length / 4) + 240,
      latencyMs: Date.now() - startTime,
      costUsd: 0.0024,
      codeSnippet: {
        language: 'typescript',
        code: `export async function processTask<T>(input: T): Promise<{ success: boolean; data: T }> {\n  // Production-grade guard clause & response mapping\n  return { success: true, data: input };\n}`,
      },
    };
  }
}
